func TestGetMessagesAndMetadataReturnEveryItem(t *testing.T) {
	dmID, secondDMID, userID := gocql.TimeUUID(), gocql.TimeUUID(), gocql.TimeUUID()
	messages := []db.DM{
		{ID: dmID, MessageID: gocql.TimeUUID(), Content: "one", Read: true},
		{ID: dmID, MessageID: gocql.TimeUUID(), Content: "two"},
	}
	metadata := []db.DMMetadata{
		{ID: dmID, UserID: userID, LastMessageTime: time.Unix(2, 0)},
		{ID: secondDMID, UserID: userID, LastMessageTime: time.Unix(1, 0)},
	}
	store := &testDMStore{messages: messages, userMetadata: metadata}
	users := &testUserStore{users: map[gocql.UUID]db.User{userID: {ID: userID}}}
	service := &directMessageService{cfg: &Config{logger: slog.Default(), signingKey: apiTestSigningKey}, store: store, users: users, friends: &testFriendStore{friend: db.Friend{ID: dmID, UserID: userID}}}

	byDM, err := service.GetMessages(authenticatedTestContext(userID), &dmsV1.GetMessagesRequest{Item: &dmsV1.DirectMessageItem{DmId: dmID.String()}})
	if err != nil {
		t.Fatal(err)
	}
	byUser, err := service.GetMessagesByUser(authenticatedTestContext(userID), &dmsV1.GetMessagesByUserRequest{})
	if err != nil {
		t.Fatal(err)
	}
	if len(byDM.Items) != len(messages) || len(byUser.Items) != len(metadata) {
		t.Fatalf("results were truncated: messages=%d metadata=%d", len(byDM.Items), len(byUser.Items))
	}
	if !byDM.Items[0].GetRead() {
		t.Fatal("message read receipt was not returned")
	}
	if byUser.Items[0].DmId != dmID.String() || !byUser.Items[0].LastMessageTime.AsTime().Equal(metadata[0].LastMessageTime) {
		t.Fatalf("unexpected metadata: %+v", byUser.Items[0])
	}
	if store.requestedDMID != dmID || store.requestedUser != userID {
		t.Fatalf("unexpected query IDs: DM=%s user=%s", store.requestedDMID, store.requestedUser)
	}
}
