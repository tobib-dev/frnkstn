package messaging

import (
	"context"
	"fmt"

	rmq "github.com/rabbitmq/rabbitmq-amqp-go-client/pkg/rabbitmqamqp"
)

func DeclareAndBindConsumer(
	ctx context.Context,
	exchangeName, routingKey, brokerURI string,
) (*rmq.Consumer, func(context.Context) error, error) {
	env := rmq.NewEnvironment(brokerURI, nil)
	conn, err := env.NewConnection(ctx)
	if err != nil {
		return nil, nil, fmt.Errorf("consumer create AMQP connection: %w", err)
	}

	if _, err := conn.Management().DeclareExchange(ctx, &rmq.TopicExchangeSpecification{
		Name: exchangeName,
	}); err != nil {
		_ = conn.Close(ctx)
		return nil, nil, fmt.Errorf("consumer declare exchange: %w", err)
	}

	qInfo, err := conn.Management().DeclareQueue(ctx, &rmq.AutoGeneratedQueueSpecification{
		IsExclusive:  true,
		IsAutoDelete: true,
	})
	if err != nil {
		_ = conn.Close(ctx)
		return nil, nil, fmt.Errorf("consumer declare queue: %w", err)
	}

	if _, err = conn.Management().Bind(ctx, &rmq.ExchangeToQueueBindingSpecification{
		SourceExchange:   exchangeName,
		DestinationQueue: qInfo.Name(),
		BindingKey:       routingKey,
	}); err != nil {
		_ = conn.Close(ctx)
		return nil, nil, fmt.Errorf("consumer bind exchange to queue: %w", err)
	}

	sub, err := conn.NewConsumer(ctx, qInfo.Name(), nil)
	if err != nil {
		_ = conn.Close(ctx)
		return nil, nil, fmt.Errorf("failed to create subscriber: %w", err)
	}

	closerFunc := func(closeCtx context.Context) error {
		subErr := sub.Close(closeCtx)
		connErr := conn.Close(closeCtx)

		if subErr != nil {
			return fmt.Errorf("close subscriber: %w", subErr)
		}
		if connErr != nil {
			return fmt.Errorf("close subscriber connection: %w", connErr)
		}
		return nil
	}

	return sub, closerFunc, nil
}
